    private static async Task<Dl1OfficialAnimationCompilerResult> WriteSyntheticAnimationsAsync(
        Dl1OfficialAnimationCompilerRequest request,
        CancellationToken cancellationToken)
    {
        Directory.CreateDirectory(request.OutputDirectory);
        var paths = ImmutableDictionary.CreateBuilder<string, string>(StringComparer.OrdinalIgnoreCase);
        foreach (PreparedCustomModelAnimation animation in request.Library.Animations)
        {
            string path = Path.Combine(request.OutputDirectory, $"{animation.Name}.anm2_obj");
            await WriteTextAsync(path, $"compiled {animation.Name}", cancellationToken);
            paths.Add(animation.Name, path);
        }

        return new Dl1OfficialAnimationCompilerResult(
            paths.ToImmutable(),
            new string('b', 64),
            "Synthetic animation compiler completed.");
    }

    private static async Task<ImmutableDictionary<string, ImmutableArray<byte>>> SnapshotProjectAsync(
        string projectRoot)
    {
        var snapshot = ImmutableDictionary.CreateBuilder<string, ImmutableArray<byte>>(
            StringComparer.OrdinalIgnoreCase);
        foreach (string path in Directory.EnumerateFiles(projectRoot, "*", SearchOption.AllDirectories)
                     .Order(StringComparer.OrdinalIgnoreCase))
        {
            string relative = Path.GetRelativePath(projectRoot, path).Replace('\\', '/');
            snapshot.Add(relative, (await File.ReadAllBytesAsync(path)).ToImmutableArray());
        }

        return snapshot.ToImmutable();
    }

    private static void AssertProjectSnapshotsEqual(
        ImmutableDictionary<string, ImmutableArray<byte>> expected,
        ImmutableDictionary<string, ImmutableArray<byte>> actual)
    {
        Assert.Equal(expected.Keys.Order(StringComparer.OrdinalIgnoreCase), actual.Keys.Order(StringComparer.OrdinalIgnoreCase));
        foreach ((string path, ImmutableArray<byte> bytes) in expected)
        {
            Assert.True(actual.TryGetValue(path, out ImmutableArray<byte> actualBytes));
            Assert.Equal(bytes.ToArray(), actualBytes.ToArray());
        }
    }

    private static async Task WriteProjectFileAsync(
