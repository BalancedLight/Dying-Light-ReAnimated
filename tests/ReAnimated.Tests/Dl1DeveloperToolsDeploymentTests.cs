    [Fact]
    [Trait("ValidationTier", "Hermetic")]
    [Trait("Gate", "CustomModelDeployment")]
    public async Task PreflightBlocksUnownedRequiredArtifactUntilExplicitReplacement()
    {
        string directory = RpackTestData.CreateTemporaryDirectory();
        try
        {
            Dl1DeveloperToolsDeploymentRequest blockedRequest = CreateDeploymentRequest(
                directory,
                installLooseAnm2: false,
                exportPortableAnimationRpack: false);
            string relativePath = "data/characters/generic_character/GenericModel.ascr";
            string existingPath = Path.Combine(
                blockedRequest.ProjectRoot,
                relativePath.Replace('/', Path.DirectorySeparatorChar));
            Directory.CreateDirectory(Path.GetDirectoryName(existingPath)!);
            await File.WriteAllTextAsync(existingPath, "unowned animation redirect");

            Dl1DeveloperToolsDeploymentPlan blocked =
                await Dl1DeveloperToolsProjectDeployer.PreflightAsync(blockedRequest);

            Assert.False(blocked.CanDeploy);
            Dl1DeveloperToolsDeploymentConflict conflict = Assert.Single(
                blocked.Conflicts.Where(conflict =>
                    string.Equals(conflict.RelativePath, relativePath, StringComparison.OrdinalIgnoreCase)));
            Assert.False(conflict.CanSkip);
            Dl1DeveloperToolsDeploymentArtifact blockedArtifact = Assert.Single(
                blocked.Artifacts.Where(artifact =>
                    string.Equals(artifact.RelativePath, relativePath, StringComparison.OrdinalIgnoreCase)));
            Assert.Equal(Dl1DeploymentArtifactDisposition.Conflict, blockedArtifact.Disposition);
            Assert.False(blockedArtifact.ExistingFileIsOwned);
            Assert.NotNull(blockedArtifact.ExistingSha256);
            Assert.NotNull(blockedArtifact.PreparedSha256);

            Dl1DeveloperToolsDeploymentRequest replaceRequest = blockedRequest with
            {
                ConflictResolutions = ImmutableDictionary<string, Dl1DeploymentConflictResolution>.Empty
                    .WithComparers(StringComparer.OrdinalIgnoreCase)
                    .Add(relativePath.ToUpperInvariant(), Dl1DeploymentConflictResolution.BackUpAndReplace),
            };
            Dl1DeveloperToolsDeploymentPlan replacement =
                await Dl1DeveloperToolsProjectDeployer.PreflightAsync(replaceRequest);

            Assert.True(replacement.CanDeploy);
            Assert.Empty(replacement.Conflicts);
            Dl1DeveloperToolsDeploymentArtifact replacementArtifact = Assert.Single(
                replacement.Artifacts.Where(artifact =>
                    string.Equals(artifact.RelativePath, relativePath, StringComparison.OrdinalIgnoreCase)));
            Assert.Equal(
                Dl1DeploymentArtifactDisposition.ReplaceUnowned,
                replacementArtifact.Disposition);
            Assert.False(replacementArtifact.ExistingFileIsOwned);
        }
        finally
        {
            RpackTestData.DeleteTemporaryDirectory(directory);
        }
    }

