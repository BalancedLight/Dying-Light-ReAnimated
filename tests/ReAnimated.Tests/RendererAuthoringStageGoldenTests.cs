            RendererAuthoringStageFixture.CreateSourceRig();
        RigDefinition targetRig =
            RendererAuthoringStageFixture.CreateTargetRig();
        RetargetMap mapping =
            RendererAuthoringStageFixture.CreateMapping(
                sourceRig,
                targetRig);
        AnimationClip bodyClip =
            RendererAuthoringStageFixture.CreateClip(
                sourceRig,
                includeAuthoredMorph: false);
        AnimationClip morphClip =
            RendererAuthoringStageFixture.CreateClip(
                sourceRig,
                includeAuthoredMorph: true);
