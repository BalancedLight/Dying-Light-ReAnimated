    private static void AssertMatchesCommittedGolden(
        IReadOnlyList<CapturedStage> captures)
    {
        string path = Path.Combine(
            FindRepositoryRoot(),
            "tests",
            "fixtures",
            "renderer_authoring_stage_goldens_v1.json");
        if (!File.Exists(path))
        {
            throw new FileNotFoundException(
                "The committed renderer authoring-stage golden is missing. " +
                "A capture output is diagnostic evidence and must not silently bless a new golden.",
                path);
        }

        byte[] bytes = File.ReadAllBytes(path);
        if (bytes.Length is <= 0 or > MaximumGoldenBytes)
        {
            throw new InvalidDataException(
                $"Renderer golden length {bytes.Length:N0} is outside the bounded 1-{MaximumGoldenBytes:N0} byte range.");
        }

        using JsonDocument document = JsonDocument.Parse(bytes);
        JsonElement root = document.RootElement;
        Assert.Equal(
            GoldenFormat,
            RequiredString(root, "format"));
        Assert.Equal(Width, RequiredInt32(root, "width"));
        Assert.Equal(Height, RequiredInt32(root, "height"));
        JsonElement stages = RequiredProperty(root, "stages");
        Assert.Equal(JsonValueKind.Array, stages.ValueKind);
        JsonElement[] expectedStages =
            stages.EnumerateArray().ToArray();
        Assert.Equal(RequiredStageNames.Length, expectedStages.Length);
        Assert.Equal(captures.Count, expectedStages.Length);
        Assert.Equal(
            RequiredStageNames,
            expectedStages.Select(
                static stage => RequiredString(stage, "name")));

        for (int index = 0; index < captures.Count; index++)
        {
            CapturedStage actual = captures[index];
            JsonElement expected = expectedStages[index];
            Assert.Equal(
                RequiredString(expected, "pixelSha256"),
                actual.PixelSha256);
            Assert.Equal(
                RequiredString(expected, "coverageSha256"),
                actual.CoverageSha256);
            Assert.Equal(
                RequiredInt32(expected, "pixelCount"),
                actual.Bounds.PixelCount);
            Assert.Equal(
                RequiredInt32(expected, "left"),
                actual.Bounds.Left);
            Assert.Equal(
                RequiredInt32(expected, "top"),
                actual.Bounds.Top);
            Assert.Equal(
                RequiredInt32(expected, "right"),
                actual.Bounds.Right);
            Assert.Equal(
                RequiredInt32(expected, "bottom"),
                actual.Bounds.Bottom);
        }
    }

    private static string WriteArtifacts(
        string outputDirectory,
        IReadOnlyList<CapturedStage> captures)
    {
        Directory.CreateDirectory(outputDirectory);
        var stages = new List<object>(captures.Count);
        foreach (CapturedStage capture in captures)
        {
            string fileName = $"{capture.Name}.bmp";
            byte[] bitmap = BuildTopDownBgraBitmap(capture.Pixels);
            WriteAtomic(
                Path.Combine(outputDirectory, fileName),
                bitmap);
            stages.Add(
                new
                {
                    capture.Name,
                    File = fileName,
                    BmpSha256 = ComputeSha256(bitmap),
                    capture.PixelSha256,
                    capture.CoverageSha256,
                    capture.Bounds.PixelCount,
                    capture.Bounds.Left,
                    capture.Bounds.Top,
                    capture.Bounds.Right,
                    capture.Bounds.Bottom,
                });
        }

        byte[] manifest = JsonSerializer.SerializeToUtf8Bytes(
            new
            {
                Format = CaptureFormat,
                GoldenFormat,
                Width,
                Height,
                Stages = stages,
            },
            ArtifactJsonOptions);
        string manifestPath =
            Path.Combine(outputDirectory, "manifest.json");
        WriteAtomic(manifestPath, manifest);
        return manifestPath;
    }

    private static byte[] BuildTopDownBgraBitmap(byte[] pixels)
    {
        int pixelBytes = checked(Width * Height * 4);
        if (pixels.Length != pixelBytes)
        {
            throw new InvalidDataException(
                $"Capture contains {pixels.Length:N0} bytes; expected {pixelBytes:N0}.");
        }

        const int headerBytes = 14 + 40;
        byte[] bitmap = new byte[checked(headerBytes + pixelBytes)];
        bitmap[0] = (byte)'B';
        bitmap[1] = (byte)'M';
        BinaryPrimitives.WriteInt32LittleEndian(
            bitmap.AsSpan(2, 4),
            bitmap.Length);
        BinaryPrimitives.WriteInt32LittleEndian(
            bitmap.AsSpan(10, 4),
            headerBytes);
        BinaryPrimitives.WriteInt32LittleEndian(
            bitmap.AsSpan(14, 4),
            40);
        BinaryPrimitives.WriteInt32LittleEndian(
            bitmap.AsSpan(18, 4),
            Width);
        BinaryPrimitives.WriteInt32LittleEndian(
            bitmap.AsSpan(22, 4),
            -Height);
        BinaryPrimitives.WriteInt16LittleEndian(
            bitmap.AsSpan(26, 2),
            1);
        BinaryPrimitives.WriteInt16LittleEndian(
            bitmap.AsSpan(28, 2),
            32);
        BinaryPrimitives.WriteInt32LittleEndian(
            bitmap.AsSpan(34, 4),
            pixelBytes);
        BinaryPrimitives.WriteInt32LittleEndian(
            bitmap.AsSpan(38, 4),
            2_835);
        BinaryPrimitives.WriteInt32LittleEndian(
            bitmap.AsSpan(42, 4),
            2_835);
        pixels.CopyTo(bitmap, headerBytes);
        return bitmap;
    }

    private static void WriteAtomic(string path, byte[] bytes)
    {
        string temporaryPath =
            path + "." + Guid.NewGuid().ToString("N") + ".tmp";
        try
        {
            File.WriteAllBytes(temporaryPath, bytes);
            File.Move(temporaryPath, path, overwrite: true);
        }
        finally
        {
            if (File.Exists(temporaryPath))
            {
                File.Delete(temporaryPath);
            }
        }
    }

    private static string FindRepositoryRoot()
    {
        string[] starts =
        [
            Directory.GetCurrentDirectory(),
            AppContext.BaseDirectory,
        ];
        foreach (string start in starts)
        {
            DirectoryInfo? current =
                new DirectoryInfo(Path.GetFullPath(start));
            while (current is not null)
            {
                if (File.Exists(
                        Path.Combine(
                            current.FullName,
                            "DLReAnimated.slnx")))
                {
                    return current.FullName;
                }

                current = current.Parent;
            }
        }

        throw new DirectoryNotFoundException(
            "Could not locate the DL ReAnimated repository root.");
    }

    private static JsonElement RequiredProperty(
        JsonElement element,
        string name) =>
        element.TryGetProperty(name, out JsonElement value)
            ? value
            : throw new InvalidDataException(
                $"Renderer golden is missing '{name}'.");

    private static string RequiredString(
        JsonElement element,
        string name) =>
        RequiredProperty(element, name).GetString() ??
        throw new InvalidDataException(
            $"Renderer golden '{name}' is null.");

    private static int RequiredInt32(
        JsonElement element,
        string name) =>
        RequiredProperty(element, name).GetInt32();

    private static string ComputeSha256(ReadOnlySpan<byte> bytes) =>
        Convert.ToHexString(SHA256.HashData(bytes))
            .ToLowerInvariant();

