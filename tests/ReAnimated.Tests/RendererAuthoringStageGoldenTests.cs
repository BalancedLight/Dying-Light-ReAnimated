        AttachmentBinding attachment =
            RendererAuthoringStageFixture.CreateAttachmentBinding();
        Dl1AuthoringPolicy rootPolicy =
            Dl1AuthoringPolicy.Create(
                sourceRig,
                targetRig,
                mapping,
                AnimationRootMode.InPlace);
        var evaluator = new AnimationEvaluator();
        double sampleTime = bodyClip.FrameRate.SecondsForFrame(1);

        EvaluationFrame retarget = Evaluate(
            evaluator,
            sourceRig,
            targetRig,
            mapping,
            bodyClip,
            sampleTime);
        Assert.True(retarget.Compatibility?.CanEvaluate);
        AssertVectorNear(
            new Vector3D(0.28, 0.08, 0.0),
            retarget.AuthoredPose.GlobalMatrices[
                RendererAuthoringStageFixture.RootBoneIndex].Translation);

        EvaluationFrame root = Evaluate(
            evaluator,
            sourceRig,
            targetRig,
            mapping,
            bodyClip,
            sampleTime,
            rootPolicy: rootPolicy);
        AssertVectorNear(
            Vector3D.Zero,
            root.AuthoredPose.GlobalMatrices[
                RendererAuthoringStageFixture.RootBoneIndex].Translation);

        EvaluationFrame edited = Evaluate(
            evaluator,
            sourceRig,
            targetRig,
            mapping,
            bodyClip,
            sampleTime,
            rootPolicy,
