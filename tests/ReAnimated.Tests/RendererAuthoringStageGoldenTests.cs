        Assert.Empty(fed.Diagnostics);
        EvaluationFrame facial = Evaluate(
            evaluator,
            sourceRig,
            targetRig,
            mapping,
            morphClip,
            sampleTime,
            rootPolicy,
            [boneEdit],
            [ik],
            morphEditLayers: [fed.Layer]);
        Assert.Equal(
            0.70,
            facial.AuthoredMorphWeights["jaw_drop"],
            6);

        var sceneLens = new CameraLens(
            68.0,
            16.0 / 9.0,
            0.02,
            100.0);
