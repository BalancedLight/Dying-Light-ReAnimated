            Math.Abs(
                QuaternionD.Dot(
                    root.AuthoredPose.LocalTransforms[
                        RendererAuthoringStageFixture.UpperArmBoneIndex]
                        .Rotation,
                    edited.AuthoredPose.LocalTransforms[
