    private sealed class WarpCaptureSession : IDisposable
    {
        private readonly ID3D11Device _device;
        private readonly ID3D11DeviceContext _context;
        private readonly ID3D11Texture2D _color;
        private readonly ID3D11RenderTargetView _renderTarget;
        private readonly ID3D11Texture2D _depth;
        private readonly ID3D11DepthStencilView _depthStencil;
        private readonly ID3D11Texture2D _staging;
        private readonly GpuSkinnedMeshRenderPass _meshPass = new();
        private readonly SkeletonRenderPass _skeletonPass = new();
        private readonly AuthoringOverlayRenderPass _authoringPass = new();
        private readonly FppSafeFrameRenderPass _fppSafeFramePass = new();
        private long _frameNumber;
        private bool _disposed;

        public WarpCaptureSession()
        {
            D3D11CreateDevice(
                null,
                DriverType.Warp,
                DeviceCreationFlags.BgraSupport,
                [FeatureLevel.Level_11_0],
                out ID3D11Device? device,
                out _,
                out ID3D11DeviceContext? context).CheckError();
            _device = device ??
                throw new InvalidOperationException(
                    "WARP returned no D3D11 device.");
            _context = context ??
                throw new InvalidOperationException(
                    "WARP returned no immediate context.");
            _color = _device.CreateTexture2D(
                CreateTextureDescription(
                    Format.B8G8R8A8_UNorm,
                    ResourceUsage.Default,
                    BindFlags.RenderTarget,
                    CpuAccessFlags.None));
            _renderTarget = _device.CreateRenderTargetView(_color);
            _depth = _device.CreateTexture2D(
                CreateTextureDescription(
                    Format.D24_UNorm_S8_UInt,
                    ResourceUsage.Default,
                    BindFlags.DepthStencil,
                    CpuAccessFlags.None));
            _depthStencil =
                _device.CreateDepthStencilView(_depth);
            _staging = _device.CreateTexture2D(
                CreateTextureDescription(
                    Format.B8G8R8A8_UNorm,
                    ResourceUsage.Staging,
                    BindFlags.None,
                    CpuAccessFlags.Read));
        }

        public CapturedStage Capture(StageScene stage)
        {
            ObjectDisposedException.ThrowIf(_disposed, this);
            ArgumentNullException.ThrowIfNull(stage);
            if (stage.Frame.ClearColor != ClearColor)
            {
                throw new InvalidDataException(
                    $"Stage '{stage.Name}' changed the matrix clear color.");
            }

            _context.OMSetRenderTargets(
                _renderTarget,
                _depthStencil);
            _context.RSSetViewport(0, 0, Width, Height);
            ClearTargets(stage.Frame.ClearColor);
            byte[] clearPixels = ReadBack();

            var diagnostics = new List<string>();
            var renderContext = new D3D11RenderFrameContext(
                _device,
                _context,
                _renderTarget,
                _depthStencil,
                Width,
                Height,
                ++_frameNumber,
                diagnostics.Add);
            _meshPass.Render(in renderContext, stage.Frame);
            _context.Flush();
            byte[] meshPixels = ReadBack();
            if (stage.VerifyCpuGpuBounds)
            {
                AssertCpuGpuBounds(stage, clearPixels, meshPixels);
            }

            if (stage.RenderSkeleton)
            {
                _skeletonPass.Render(in renderContext, stage.Frame);
            }

            if (stage.RenderAuthoringOverlay)
            {
                _authoringPass.Render(in renderContext, stage.Frame);
            }

            if (stage.RenderFppSafeFrame)
            {
                _fppSafeFramePass.Render(in renderContext, stage.Frame);
            }

            _context.Flush();
            if (diagnostics.Count > 0)
            {
                throw new InvalidOperationException(
                    $"Stage '{stage.Name}' produced renderer diagnostics: " +
                    string.Join(" | ", diagnostics));
            }

            byte[] pixels = ReadBack();
            (PixelBounds bounds, byte[] coverageMask) =
                MeasureCoverage(clearPixels, pixels);
            if (bounds.PixelCount <= 0)
            {
                throw new InvalidOperationException(
                    $"Stage '{stage.Name}' rendered no changed pixels.");
            }

            return new CapturedStage(
                stage.Name,
                pixels,
                bounds,
                ComputeSha256(pixels),
                ComputeSha256(coverageMask));
        }

        public void ThrowIfDeviceWasRemoved()
        {
            ObjectDisposedException.ThrowIf(_disposed, this);
            _device.DeviceRemovedReason.CheckError();
        }

        public void Dispose()
        {
            if (_disposed)
            {
                return;
            }

            _disposed = true;
            _fppSafeFramePass.Dispose();
            _authoringPass.Dispose();
            _skeletonPass.Dispose();
            _meshPass.Dispose();
            _staging.Dispose();
            _depthStencil.Dispose();
            _depth.Dispose();
            _renderTarget.Dispose();
            _color.Dispose();
            _context.Dispose();
            _device.Dispose();
        }

        private static void AssertCpuGpuBounds(
            StageScene stage,
            byte[] clearPixels,
            byte[] meshPixels)
        {
            PixelBounds gpu =
                MeasureCoverage(clearPixels, meshPixels).Bounds;
            PixelBounds cpu = MeasureCpuProjectedBounds(
                stage.Frame);
            Assert.True(
                gpu.PixelCount > 0,
                $"Stage '{stage.Name}' produced no mesh pixels before overlays.");
            Assert.InRange(Math.Abs(gpu.Left - cpu.Left), 0, 3);
            Assert.InRange(Math.Abs(gpu.Top - cpu.Top), 0, 3);
            Assert.InRange(Math.Abs(gpu.Right - cpu.Right), 0, 3);
            Assert.InRange(Math.Abs(gpu.Bottom - cpu.Bottom), 0, 3);
        }

        private static PixelBounds MeasureCpuProjectedBounds(
            RenderFrameSnapshot frame)
        {
            var projected = new List<Vector2>();
            Matrix4x4 viewProjection =
                RenderCameraMath.CreateViewProjection(
                    frame.Camera,
                    Width,
                    Height);
            foreach (MeshRenderData mesh in frame.Meshes)
            {
                CpuDeformedVertex[] vertices =
                    CpuMeshDeformationEvaluator.Evaluate(
                        mesh,
                        mesh.IsSkinned
                            ? frame.Skeleton
                            : null,
                        frame.MorphWeights);
                projected.AddRange(
                    vertices.Select(vertex =>
                        Project(vertex.Position, viewProjection)));
            }

            if (projected.Count == 0)
            {
                throw new InvalidDataException(
                    "A CPU/GPU bounds stage has no projected vertices.");
            }

            return new PixelBounds(
                checked((int)MathF.Floor(
                    projected.Min(static point => point.X))),
                checked((int)MathF.Floor(
                    projected.Min(static point => point.Y))),
                checked((int)MathF.Ceiling(
                    projected.Max(static point => point.X))),
                checked((int)MathF.Ceiling(
                    projected.Max(static point => point.Y))),
                0);
        }

        private static Vector2 Project(
            Vector3 position,
            Matrix4x4 viewProjection)
        {
            Vector4 clip = Vector4.Transform(
                new Vector4(position, 1.0f),
                viewProjection);
            if (!float.IsFinite(clip.X) ||
                !float.IsFinite(clip.Y) ||
                !float.IsFinite(clip.W) ||
                MathF.Abs(clip.W) <= 1.0e-8f)
            {
                throw new InvalidDataException(
                    "The CPU reference produced a non-projectable vertex.");
            }

            Vector2 normalized =
                new(clip.X / clip.W, clip.Y / clip.W);
            return new Vector2(
                (normalized.X * 0.5f + 0.5f) * Width,
                (-normalized.Y * 0.5f + 0.5f) * Height);
        }

        private static (
            PixelBounds Bounds,
            byte[] CoverageMask) MeasureCoverage(
                byte[] clearPixels,
                byte[] pixels)
        {
            if (clearPixels.Length != pixels.Length ||
                pixels.Length != Width * Height * 4)
            {
                throw new InvalidDataException(
                    "Renderer readback dimensions changed during capture.");
            }

            int left = Width;
            int top = Height;
            int right = -1;
            int bottom = -1;
            int count = 0;
            byte[] mask =
                new byte[(Width * Height + 7) / 8];
            for (int pixelIndex = 0;
                 pixelIndex < Width * Height;
                 pixelIndex++)
            {
                int byteIndex = pixelIndex * 4;
                bool changed =
                    pixels[byteIndex] != clearPixels[byteIndex] ||
                    pixels[byteIndex + 1] !=
                        clearPixels[byteIndex + 1] ||
                    pixels[byteIndex + 2] !=
                        clearPixels[byteIndex + 2];
                if (!changed)
                {
                    continue;
                }

                mask[pixelIndex >> 3] |=
                    checked((byte)(1 << (pixelIndex & 7)));
                int x = pixelIndex % Width;
                int y = pixelIndex / Width;
                left = Math.Min(left, x);
                top = Math.Min(top, y);
                right = Math.Max(right, x);
                bottom = Math.Max(bottom, y);
                count++;
            }

            return (
                new PixelBounds(
                    left,
                    top,
                    right,
                    bottom,
                    count),
                mask);
        }

        private void ClearTargets(Vector4 clearColor)
        {
            _context.ClearRenderTargetView(
                _renderTarget,
                new Color4(
                    clearColor.X,
                    clearColor.Y,
                    clearColor.Z,
                    clearColor.W));
            _context.ClearDepthStencilView(
                _depthStencil,
                DepthStencilClearFlags.Depth,
                1.0f,
                0);
        }

        private byte[] ReadBack()
        {
            _context.CopyResource(_staging, _color);
            _context.Flush();
            _context.Map(
                _staging,
                0,
                MapMode.Read,
                Vortice.Direct3D11.MapFlags.None,
                out MappedSubresource mapped).CheckError();
            try
            {
                byte[] pixels =
                    new byte[Width * Height * 4];
                int rowBytes = Width * 4;
                for (int row = 0; row < Height; row++)
                {
                    Marshal.Copy(
                        IntPtr.Add(
                            mapped.DataPointer,
                            checked((int)(row * mapped.RowPitch))),
                        pixels,
                        row * rowBytes,
                        rowBytes);
                }

                return pixels;
            }
            finally
            {
                _context.Unmap(_staging, 0);
            }
        }

        private static Texture2DDescription CreateTextureDescription(
            Format format,
            ResourceUsage usage,
            BindFlags bindFlags,
            CpuAccessFlags cpuAccessFlags) =>
            new()
            {
                Width = Width,
                Height = Height,
                MipLevels = 1,
                ArraySize = 1,
                Format = format,
                SampleDescription = new SampleDescription(1, 0),
                Usage = usage,
                BindFlags = bindFlags,
                CPUAccessFlags = cpuAccessFlags,
                MiscFlags = ResourceOptionFlags.None,
            };
    }
