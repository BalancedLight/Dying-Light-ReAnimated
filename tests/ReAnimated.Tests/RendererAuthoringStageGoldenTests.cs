    [Fact]
    [Trait("Category", "Renderer")]
    [Trait("Gate", "RendererAuthoringGoldens")]
    public void WarpAuthoringStagesMatchRedistributableGoldenMatrix()
    {
        AuthoringMatrix matrix = BuildAuthoringMatrix();
        Assert.Equal(RequiredStageNames, matrix.Stages.Select(
            static stage => stage.Name));

        using var captureSession = new WarpCaptureSession();
        CapturedStage[] captures = matrix.Stages
            .Select(captureSession.Capture)
            .ToArray();
        captureSession.ThrowIfDeviceWasRemoved();

        Assert.Equal(
            captures.Length,
            captures
                .Select(static capture => capture.PixelSha256)
                .Distinct(StringComparer.Ordinal)
                .Count());
        Assert.Equal(
            captures.Length,
            captures
                .Select(static capture => capture.CoverageSha256)
                .Distinct(StringComparer.Ordinal)
                .Count());

        foreach (CapturedStage capture in captures)
        {
            _output.WriteLine(
                string.Create(
                    CultureInfo.InvariantCulture,
                    $"{capture.Name}: pixels={capture.Bounds.PixelCount}, bounds={capture.Bounds.Left},{capture.Bounds.Top}-{capture.Bounds.Right},{capture.Bounds.Bottom}, pixelsSha256={capture.PixelSha256}, coverageSha256={capture.CoverageSha256}"));
        }

        string? outputDirectory =
            Environment.GetEnvironmentVariable(
                "DLR_RENDERER_GOLDEN_OUTPUT");
        if (!string.IsNullOrWhiteSpace(outputDirectory))
        {
            string manifestPath = WriteArtifacts(
                Path.GetFullPath(
                    Environment.ExpandEnvironmentVariables(
                        outputDirectory.Trim())),
                captures);
            _output.WriteLine(
                $"Inspectable renderer captures: {manifestPath}");
        }

        AssertMatchesCommittedGolden(captures);
    }

