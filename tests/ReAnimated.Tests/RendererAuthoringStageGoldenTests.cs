    private static EvaluationFrame Evaluate(
        AnimationEvaluator evaluator,
        RigDefinition sourceRig,
        RigDefinition targetRig,
        RetargetMap mapping,
        AnimationClip clip,
        double timeSeconds,
        Dl1AuthoringPolicy? rootPolicy = null,
        IEnumerable<BoneEditLayer>? editLayers = null,
        IEnumerable<IkConstraintLayer>? ikLayers = null,
        IEnumerable<MorphEditLayer>? morphEditLayers = null,
        PreviewProfile? previewProfile = null,
        Dl1PreviewInputs? previewInputs = null,
        IEnumerable<AttachmentBinding>? attachments = null) =>
        evaluator.Evaluate(
            new EvaluationRequest(
                sourceRig,
                targetRig,
                clip,
                timeSeconds,
                previewProfile ?? PreviewProfile.RawAuthoring,
                mapping,
                editLayers,
                purpose: EvaluationPurpose.Preview,
                attachments: attachments,
                dl1AuthoringPolicy: rootPolicy,
                morphEditLayers: morphEditLayers,
                ikLayers: ikLayers,
                dl1PreviewInputs: previewInputs));

    private static RenderFrameSnapshot CreateOrbitFrame(
        EvaluationFrame evaluation,
        MeshRenderData actor) =>
        CreateFrame(
            evaluation,
            [actor],
            RendererAuthoringStageFixture.OrbitCamera);

    private static RenderFrameSnapshot CreateFrame(
        EvaluationFrame evaluation,
        IReadOnlyList<MeshRenderData> meshes,
        RenderCamera camera) =>
        new(
            ClearColor,
            camera,
            meshes,
            CorePreviewAdapter.ToRenderSkeleton(
                evaluation.DisplayPose),
            [],
            ToMorphWeights(evaluation.DisplayMorphWeights));

    private static MorphWeight[] ToMorphWeights(
        IReadOnlyDictionary<string, double> weights) =>
        weights
            .OrderBy(static pair => pair.Key, StringComparer.Ordinal)
            .Select(static pair =>
                new MorphWeight(
                    pair.Key,
                    checked((float)pair.Value)))
            .ToArray();

    private static Vector3[] SampleRawRootTrail(
        AnimationEvaluator evaluator,
        RigDefinition sourceRig,
        RigDefinition targetRig,
        RetargetMap mapping,
        AnimationClip bodyClip) =>
        RootTrailFrames
            .Select(frame =>
                Evaluate(
                    evaluator,
                    sourceRig,
                    targetRig,
                    mapping,
                    bodyClip,
                    bodyClip.FrameRate.SecondsForFrame(frame))
                .DisplayPose.GlobalMatrices[
                    RendererAuthoringStageFixture.RootBoneIndex]
                .Translation)
            .Select(ToVector3)
            .ToArray();

